#!/usr/bin/env node
/* Reads LeetCode notes from the Obsidian vault and writes js/leetcode-data.js.
 *
 *   node tools/sync-leetcode.js "/path/to/Vault" ["4 - Main Notes/Leetcode"]
 *
 * The app merges a newer snapshot into what's saved in the browser on its
 * next load: code and notes update, practice history is kept.
 */
const fs = require('fs');
const path = require('path');
const { parseLeetcodeNote } = require('../js/leetcode-parse.js');

const vaultArg = process.argv[2] || process.env.OBSIDIAN_VAULT;
if (!vaultArg) {
  console.error('Usage: node tools/sync-leetcode.js "/path/to/Vault" ["4 - Main Notes/Leetcode"]\nOr set OBSIDIAN_VAULT to your vault path.');
  process.exit(1);
}
const vault = path.resolve(vaultArg);
const folder = process.argv[3] || '4 - Main Notes/Leetcode';
const root = path.join(vault, folder);

if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
  console.error(`No folder at ${root}`);
  process.exit(1);
}

const ymd = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.isFile() && /\.md$/i.test(e.name) ? [p] : [];
  });
}

const problems = [];
const skipped = [];
for (const file of walk(root)) {
  const st = fs.statSync(file);
  // birthtime is when the note was written; fall back to mtime where it isn't tracked
  const born = st.birthtimeMs > 0 && st.birthtimeMs <= st.mtimeMs ? st.birthtime : st.mtime;
  const rel = path.relative(vault, file).split(path.sep).join('/');
  const p = parseLeetcodeNote({ path: rel, text: fs.readFileSync(file, 'utf8'), date: ymd(born) });
  if (p) problems.push(p);
  else skipped.push(rel);
}
problems.sort((a, b) => a.num - b.num);

const snapshot = { vault: path.basename(vault), generated: new Date().toISOString(), problems };
const out = path.join(__dirname, '..', 'js', 'leetcode-data.js');
fs.writeFileSync(
  out,
  `/* Generated by tools/sync-leetcode.js from the Obsidian vault. Re-run it after solving more problems. */\n` +
    `const LEETCODE_SNAPSHOT = ${JSON.stringify(snapshot, null, 1)};\n`
);

const by = (d) => problems.filter((p) => p.difficulty === d).length;
console.log(`Wrote ${problems.length} problems (${by('Easy')} easy, ${by('Medium')} medium, ${by('Hard')} hard) to ${path.relative(process.cwd(), out)}`);
if (skipped.length) console.log(`Skipped (name isn't "<number>. <title>.md"): ${skipped.join(', ')}`);
const other = problems.filter((p) => p.pattern === 'Other');
if (other.length) console.log(`No pattern guessed for: ${other.map((p) => p.num).join(', ')} (set it in the app)`);
